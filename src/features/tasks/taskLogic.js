import { COLOR_PALETTE } from '../../constants/colorPalette'

// Pure date/classification helpers for the tasks feature — no React, no
// store access, so they're trivially testable and reusable from both the
// page and the modal.

// Projects created before color-coding was added won't have a `.color` —
// falls back to a color derived from a hash of its id, so it's stable
// across renders/lists (unlike a list-position index, which shifts with
// sorting/filtering) and never shows an uncolored/blank swatch.
export function getProjectColor(project) {
  if (project?.color) return project.color
  if (!project?.id) return COLOR_PALETTE[0]
  let hash = 0
  for (let i = 0; i < project.id.length; i++) hash = (hash * 31 + project.id.charCodeAt(i)) | 0
  return COLOR_PALETTE[Math.abs(hash) % COLOR_PALETTE.length]
}

export function isoFromDate(d) {
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

export function todayISO() {
  return isoFromDate(new Date())
}

export function addDays(iso, n) {
  const d = new Date(`${iso}T00:00:00`)
  d.setDate(d.getDate() + n)
  return isoFromDate(d)
}

export function addMonths(iso, n) {
  const d = new Date(`${iso}T00:00:00`)
  d.setMonth(d.getMonth() + n)
  return isoFromDate(d)
}

// Next date (strictly after `base`) whose day-of-week matches `dow` (0=Sun..6=Sat).
export function nextWeekdayDate(base, dow) {
  for (let i = 1; i <= 7; i++) {
    const candidate = addDays(base, i)
    if (new Date(`${candidate}T00:00:00`).getDay() === dow) return candidate
  }
  return base
}

// Next date (strictly after `base`) whose day-of-week is in `days` (0=Sun..6=Sat)
// — used by the 'custom' (selective weekdays) recurrence. Falls back to a
// week out if `days` is empty, ported from the task-manager prototype so a
// recurring task never silently stops advancing.
export function nextCustomDate(base, days) {
  if (!days || !days.length) return addDays(base, 7)
  for (let i = 1; i <= 7; i++) {
    const candidate = addDays(base, i)
    const dow = new Date(`${candidate}T00:00:00`).getDay()
    if (days.includes(dow)) return candidate
  }
  return addDays(base, 7)
}

// InsightsChat's "--" autoformat (per user request — typing two dashes in
// the composer turns into a task-line marker, Notion-style) and the bubble
// color that follows from it (see .insights-chat__bubble--task in index.css).
// Clicking the circle toggles a line between the two bullets (per user
// report — the circle used to be inert text, they need to actually check
// tasks off), which is why the done state lives in the bullet character
// itself rather than separate structured data — the store only ever
// persists message.text.
export const TASK_BULLET = '○ '
export const TASK_BULLET_DONE = '● '

export function isTaskLine(line) {
  return line.startsWith(TASK_BULLET) || line.startsWith(TASK_BULLET_DONE)
}

export function isTaskLineDone(line) {
  return line.startsWith(TASK_BULLET_DONE)
}

export function taskLineText(line) {
  return line.startsWith(TASK_BULLET_DONE) ? line.slice(TASK_BULLET_DONE.length)
    : line.startsWith(TASK_BULLET) ? line.slice(TASK_BULLET.length)
    : line
}

export function messageHasTask(text) {
  if (!text) return false
  return text.split('\n').some(isTaskLine)
}

// Daily reset for the Analysis checklist (see usePrinciplesStore.js) —
// clears every checked box back to open without touching item text or
// line order.
export function resetTaskLines(text) {
  return text
    .split('\n')
    .map((line) => (isTaskLineDone(line) ? TASK_BULLET + taskLineText(line) : line))
    .join('\n')
}

export function allTaskLinesDone(text) {
  const lines = text.split('\n').filter(isTaskLine)
  return lines.length === 0 || lines.every(isTaskLineDone)
}

// Drives usePrinciplesStore's daily reset (see
// docs/superpowers/specs/2026-08-29-daily-principles-reset-design.md) — a
// pure function so it's testable without touching Zustand/Firestore.
// `messages` is the store's current message list, `lastReset` its
// persisted last-reset date, `today` the caller's todayISO(), `promptText`
// the fixed daily journal prompt. Returns null when today's reset already
// ran (nothing to do); otherwise the replacement { messages,
// lastPrinciplesReset } to write back into the store.
export function computeDailyPrinciplesReset(messages, lastReset, today, promptText) {
  if (lastReset === today) return null

  const isPrompt = (m) => m.type === 'text' && m.text === promptText
  const isChecklist = (m) => m.type === 'text' && messageHasTask(m.text)

  const checklist = [...messages].reverse().find(isChecklist)
  const kept = messages.filter((m) => !isPrompt(m) && !isChecklist(m))

  const now = Date.now()
  // autoGenerated: true — this is a daily reset repost, not something the
  // user actually wrote today. Lets anything checking "did the user add a
  // message today" (see dailyRoutineTasks.js's "Дневник" routine task)
  // tell the two apart instead of reading every reset as fresh journal
  // activity.
  const freshMessage = (text, offsetMs) => ({
    id: crypto.randomUUID(),
    type: 'text',
    text,
    mediaUrl: null,
    durationSec: null,
    createdAt: new Date(now + offsetMs).toISOString(),
    editedAt: null,
    done: false,
    autoGenerated: true,
  })

  const fresh = [...kept, freshMessage(promptText, 0)]
  if (checklist) fresh.push(freshMessage(resetTaskLines(checklist.text), 1))

  return { messages: fresh, lastPrinciplesReset: today }
}

// Shift+Enter continuation for a task-bullet line (see InsightsChat.jsx's
// composer/edit textareas) — pressing Enter on a bullet line with text
// starts a fresh bullet on the next line; on an empty bullet line it strips
// the bullet instead (same "blank line ends the list" convention as
// Notes/Notion), rather than piling up empty bullets forever. Returns null
// when the current line isn't a task line at all, so callers fall through
// to the textarea's own default Enter behavior.
export function insertTaskContinuation(value, cursor) {
  const lineStart = value.lastIndexOf('\n', cursor - 1) + 1
  const currentLine = value.slice(lineStart, cursor)
  if (!isTaskLine(currentLine)) return null
  if (taskLineText(currentLine).trim() === '') {
    return { value: value.slice(0, lineStart) + value.slice(cursor), cursor: lineStart }
  }
  const insertion = '\n' + TASK_BULLET
  return { value: value.slice(0, cursor) + insertion + value.slice(cursor), cursor: cursor + insertion.length }
}

export function toggleTaskLineInText(text, lineIndex) {
  const lines = text.split('\n')
  const line = lines[lineIndex]
  if (line === undefined) return text
  if (line.startsWith(TASK_BULLET_DONE)) lines[lineIndex] = TASK_BULLET + line.slice(TASK_BULLET_DONE.length)
  else if (line.startsWith(TASK_BULLET)) lines[lineIndex] = TASK_BULLET_DONE + line.slice(TASK_BULLET.length)
  return lines.join('\n')
}

