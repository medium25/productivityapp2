// Next occurrence date for a recurring task, or null if it doesn't repeat.
// Bases off the task's own whenDate when that's still in the future (a
// habit completed early keeps its real cadence instead of jumping off
// today), but never off a *past* whenDate — an overdue habit stays parked
// in My day until it's checked off (see classifyActionColumn), so basing
// the next occurrence off its stale date could still land on today or
// even another past day, making the freshly spawned copy pop right back
// into My day instead of waiting for the next real day.
export function nextOccurrenceDate(task) {
  const today = todayISO()
  const base = (task.whenDate && task.whenDate > today) ? task.whenDate : today
  if (task.recurrence === 'daily') return addDays(base, 1)
  if (task.recurrence === 'custom') return nextCustomDate(base, task.recurrenceDays || [])
  if ((task.recurrence === 'weekly' || task.recurrence === 'monthly') && task.recurrenceDays?.length) return nextRecurringDate(task, addDays(base, 1))
  if (task.recurrence === 'weekly') return addDays(base, 7)
  if (task.recurrence === 'monthly') return addMonths(base, 1)
  return null
}

// Whether a recurring task's pattern lands on `iso` — daily always, weekly/
// monthly anchored on the task's own whenDate (its weekday / day-of-month),
// custom on its chosen weekdays.
// First date on or after `fromIso` the pattern lands on (null if none within ~2 years).
export function nextRecurringDate(task, fromIso) {
  let iso = fromIso
  for (let n = 0; n < 800; n += 1) {
    if (recursOnDate(task, iso)) return iso
    iso = addDays(iso, 1)
  }
  return null
}

export function recursOnDate(task, iso) {
  if (!task.recurrence || task.recurrence === 'none') return false
  if (task.recurrence === 'daily') return true
  const d = new Date(`${iso}T00:00:00`)
  if (task.recurrence === 'custom') return (task.recurrenceDays || []).includes(d.getDay())
  // Weekly / monthly with a chosen day: recurrenceDays = [weekday] / [day of month]
  // (a day past the month's end lands on its last day).
  if (task.recurrence === 'weekly' && task.recurrenceDays?.length) return task.recurrenceDays.includes(d.getDay())
  if (task.recurrence === 'monthly' && task.recurrenceDays?.length) {
    const last = new Date(d.getFullYear(), d.getMonth() + 1, 0).getDate()
    return d.getDate() === Math.min(task.recurrenceDays[0], last)
  }
  if (!task.whenDate) return false
  const anchor = new Date(`${task.whenDate}T00:00:00`)
  if (task.recurrence === 'weekly') return anchor.getDay() === d.getDay()
  if (task.recurrence === 'monthly') return anchor.getDate() === d.getDate()
  return false
}

// GTD triage stage — 'inbox' (uncaptured/untriaged), 'later' (someday/
// maybe), or 'tasks' (actionable, has a deadline). Tasks created before the
// GTD board existed have no `.stage` — derived here instead of migrated in
// place, so it degrades safely regardless of when/if a row gets rewritten:
// a dated task is assumed already-triaged ('tasks'), an undated one hasn't
// been looked at yet ('inbox').
export function getTaskStage(task) {
  return task.stage || (task.whenDate ? 'tasks' : 'inbox')
}

// Classifies a task into one of five buckets used to group the tasks page.
// `done` tasks are filtered out by the caller before this even matters.
// No "без дедлайна"/someday bucket — a task with no date is 'unsorted'.
// 'future' (>7 days out) is a dynamic section on the page: rendered only
// while it actually has a card in it, gone otherwise — a task only ends up
// there by explicitly picking a distant date, never a default.
export function classifyTask(task, today = todayISO()) {
  if (task.status === 'done') return 'done'
  if (!task.whenDate) return 'unsorted'
  if (task.whenDate === today) return 'today'
  if (task.whenDate < today) return 'today' // overdue, still shown under today until rescheduled
  const tomorrow = addDays(today, 1)
  if (task.whenDate === tomorrow) return 'tomorrow'
  const weekAhead = addDays(today, 7)
  if (task.whenDate <= weekAhead) return 'week'
  return 'future'
}

// Inverse of classifyTask for the 4 sections a task can be dropped/moved
// into (drag-and-drop between sections, and the modal's "Перевести" jump) —
// 'week' just needs any date more than a day out, +2 is an arbitrary pick
// within that range. Shared so both call sites can't drift apart.
export function whenDateForSection(sectionKey, today = todayISO()) {
  if (sectionKey === 'today') return today
  if (sectionKey === 'tomorrow') return addDays(today, 1)
  if (sectionKey === 'week') return addDays(today, 2)
  return null // 'unsorted'
}

// Classifies a task into one of the 3 date-only buckets that back the My
// day / Upcoming / Sometime sections (see ActionColumnBoard.jsx). Projects
// have no date at all, so they always live in "sometime" by construction,
// never classified through this function. A task due today stays in
// "myday" through that whole day, but once the deadline day has passed
// without it being done, the next day it automatically drops out of My day
// into "sometime" (per user request) rather than lingering there
// indefinitely — it still has a (past) whenDate, so it still shows in the
// Inbox section's flat Tasks list too, same as any other dated task (see
// InboxPage.jsx). A task with no whenDate at all lands in "sometime" the
// same way, but per user request does NOT also show in Inbox — that list
// excludes undated tasks specifically so they aren't duplicated there.
//
// An overdue task (recurring or not) stays classified as 'myday' rather
// than sliding into Sometime — per user request, a stale task should keep
// accumulating where it's visible (Upcoming's "Overdue" group, see
// ActionColumnBoard.jsx's dateGroups) instead of quietly dropping out of
// the actionable view into Sometime. Recurring vs one-off only matters for
// *where inside* Upcoming it lands: a recurring habit collapses into
// today's group (completing it is what advances it — toggleTaskDone spawns
// the next occurrence and marks this one done, not the calendar rolling
// over underneath it), while a one-off task piles up in the Overdue group
// until it's actually done or rescheduled.
export function classifyActionColumn(task, today = todayISO()) {
  if (!task.whenDate) return 'sometime'
  if (task.whenDate === today) return 'myday'
  if (task.whenDate < today) return 'myday'
  return 'upcoming'
}

// Inverse of classifyActionColumn, for drag-and-drop and quick-add between
// the 3 buckets. "upcoming" needs *some* concrete date to drop a task on —
// tomorrow is the nearest one that's unambiguously "not today".
export function whenDateForActionColumn(columnKey, today = todayISO()) {
  if (columnKey === 'myday') return today
  if (columnKey === 'upcoming') return addDays(today, 1)
  return null // 'sometime'
}

// The field patch that lands a task in a given top-level section when it's
// dragged onto that section's sidebar link (see Sidebar.jsx's
// data-drop-section, useDragReorder.js's onCrossDropSection) — per user
// request, any task should be draggable into any section from anywhere,
// not just reordered within whichever list it started in. Inbox's own flat
// list structurally excludes project-assigned tasks (see InboxPage.jsx) and
// (per its own stricter filter) only ever shows genuinely undated
// stage:'inbox' captures — so that's the one target that also clears
// projectId/whenDate/deadline outright, filing the task back to a fresh
// capture rather than leaving it invisible there with a stale date.
//
// 'upcoming' deliberately has no `whenDate` here (unlike the 'inbox'/
// 'sometime' branches, which explicitly set/clear it) — per user request,
// dropping an undated task onto Tasks must not silently default to
// tomorrow. Every onCrossDropSection call site routes through
// useSectionDropDateGate.js instead of calling this directly: an
// already-dated task's whenDate survives untouched (this patch just leaves
// it out, so updateTask's spread-merge doesn't overwrite it), while an
// undated one gets asked via DueRequiredPrompt.jsx before the move
// actually happens.
export function patchForSectionMove(sectionKey) {
  if (sectionKey === 'inbox') return { whenDate: null, deadline: null, projectId: null, stage: 'inbox' }
  if (sectionKey === 'upcoming') return { stage: 'tasks' }
  // 'now' — the Inbox page's own "drag to Now" drop zone (see
  // TasksInboxPage.jsx). Unlike 'upcoming' (any future date, ambiguous
  // enough to need DueRequiredPrompt asking which one) "now" means today
  // specifically, so it's fine to apply straight away with no prompt.
  if (sectionKey === 'now') return { stage: 'tasks', whenDate: todayISO() }
  if (sectionKey === 'sometime') return { whenDate: null, stage: 'tasks' }
  // 'wishes' — the Inbox page's own "drag to Wishes" drop zone (see
  // TasksInboxPage.jsx) and the Tasks hub's own Wishes card
  // (TasksWishesPage.jsx). Reuses the 'later' stage GtdBoardPage.jsx's
  // Someday/Maybe column already writes — distinct from plain undated
  // Inbox tasks (stage 'tasks', no whenDate): this is for something
  // deliberately deferred, not just not-yet-dated.
  if (sectionKey === 'wishes') return { whenDate: null, stage: 'later' }
  return {}
}

export function isOverdue(task, today = todayISO()) {
  return !!task.deadline && task.status === 'active' && task.deadline < today
}

// Same 3-way split as classifyActionColumn, but for a project's own
// `deadline` field (see useTasksStore's setProjectDeadline) instead of a
// task's whenDate — lets a project slot into the Tasks board's Today/Future
// columns once it has a due date; with none it stays in Wishes, per user
// request.
export function classifyProjectColumn(project, today = todayISO()) {
  if (!project.deadline) return 'sometime'
  if (project.deadline <= today) return 'myday'
  return 'upcoming'
}

// "чч:мм" -> minutes, or null if the field is empty. Returns undefined for
// an unparsable non-empty string so callers can distinguish "no input" from
// "bad input" and show a validation message only for the latter.
export function parseEstimateInput(str) {
  const trimmed = (str || '').trim()
  if (!trimmed) return null
  const m = trimmed.match(/^(\d{1,3}):([0-5]\d)$/)
  if (!m) return undefined
  const minutes = parseInt(m[1], 10) * 60 + parseInt(m[2], 10)
  return minutes || null
}

export function formatEstimateInput(minutes) {
  if (!minutes) return ''
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`
}

// Short badge label, e.g. "1ч 30м" / "45м".
export function formatEstimateLabel(minutes) {
  if (!minutes) return null
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  if (h === 0) return `${m}м`
  if (m === 0) return `${h}ч`
  return `${h}ч ${m}м`
}

// Short human date label used on badges — delegates the "today"/"tomorrow"
// wording to the caller via `t` so it stays translated in all 3 languages;
// falls back to `Intl.DateTimeFormat` (driven by the active i18n language)
// for any other date, so month abbreviations follow the current locale too.
export function formatDateBadge(iso, t, language, today = todayISO()) {
  if (!iso) return ''
  if (iso === today) return t('tasks.today')
  if (iso === addDays(today, 1)) return t('tasks.tomorrow')
  if (iso === addDays(today, -1)) return t('tasks.yesterday')
  const d = new Date(`${iso}T00:00:00`)
  try {
    return new Intl.DateTimeFormat(language, { day: 'numeric', month: 'short' }).format(d)
  } catch {
    return new Intl.DateTimeFormat('ru', { day: 'numeric', month: 'short' }).format(d)
  }
}

// Same hash-into-COLOR_PALETTE pattern as getProjectColor, keyed on the tag
// string itself so a given tag always renders the same color everywhere
// (sidebar, card badges, tag page) without needing to persist a color.
export function getTagColor(tag) {
  let hash = 0
  for (let i = 0; i < tag.length; i++) hash = (hash * 31 + tag.charCodeAt(i)) | 0
  return COLOR_PALETTE[Math.abs(hash) % COLOR_PALETTE.length]
}

// Identity of a recurring task's series — title, cycle and chosen weekdays. The
// app keeps exactly one live record per series (see rollRecurringToToday), so
// copies, re-created routines and stale records never pile up in Today.
export function seriesKey(task) {
  return [
    (task.title || '').trim().toLowerCase(),
    task.recurrence,
    (task.recurrenceDays || []).slice().sort().join(','),
  ].join('|')
}
