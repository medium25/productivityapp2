// Mishary Rashid Alafasy ("afs"), full-surah recitation — streamed from
// mp3quran.net's CDN on demand instead of shipping ~800 MB of audio in the
// repo or the app bundle. Same reciter as the user's own local files.
// Surah number is zero-padded to 3 digits (001..114). This host sends CORS
// headers and supports HTTP Range requests, so seeking mid-surah works.
export function surahAudioUrl(n) {
  return `https://server8.mp3quran.net/afs/${String(n).padStart(3, '0')}.mp3`
}

export function getSurah(n) {
  return SURAHS[n - 1]
}
